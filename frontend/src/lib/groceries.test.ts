import { describe, expect, it } from 'vitest';
import { groceryDepartment } from './groceries';

describe('grocery departments', () => {
  it.each([
    ['Куриная грудка', 'Мясо и рыба'], ['pierś z kurczaka', 'Мясо и рыба'],
    ['Йогурт', 'Молочное и яйца'], ['яйца', 'Молочное и яйца'], ['mleko', 'Молочное и яйца'],
    ['Сливочное масло', 'Молочное и яйца'], ['растительное масло', 'Бакалея'],
    ['фасоль', 'Бакалея'], ['чечевица', 'Бакалея'], ['грецкие орехи', 'Бакалея'],
    ['картофель', 'Овощи и фрукты'], ['Помидоры', 'Овощи и фрукты'], ['салат', 'Овощи и фрукты'],
    ['ягоды', 'Овощи и фрукты'], ['sałata', 'Овощи и фрукты'], ['broccoli', 'Овощи и фрукты'],
    ['chleb', 'Крупы и хлеб'], ['рыба', 'Мясо и рыба'], ['кристаллы соли', 'Другие покупки'],
  ])('%s', (title, department) => expect(groceryDepartment(title)).toEqual(department));
});
